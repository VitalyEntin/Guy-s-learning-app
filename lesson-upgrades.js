  const letterByName = Object.fromEntries(letters.map((item) => [item[0], item]));
  const pool = letters.map((item) => item[1]);

  function wrongLetters(answer, offset) {
    return pool.filter((item) => item !== answer).slice(offset, offset + 3);
  }

  function letterLesson(id, title, names, points) {
    const selected = names.map((name) => letterByName[name]);
    const questions = [];
    selected.forEach(([name, letter], index) => questions.push(q({ prompt: `Найди ${name}`, answer: letter, wrongs: wrongLetters(letter, index) })));
    selected.forEach(([name, letter, sound], index) => questions.push(q({ prompt: `Где звук «${sound}»?`, answer: letter, wrongs: wrongLetters(letter, index + 5) })));
    selected.forEach(([name, letter], index) => questions.push(q({ prompt: `Буква ${name}`, answer: letter, wrongs: wrongLetters(letter, index + 10) })));
    while (questions.length < 15) {
      const [name, letter] = selected[questions.length % selected.length];
      questions.push(q({ prompt: `Найди ${name} снова`, answer: letter, wrongs: wrongLetters(letter, questions.length) }));
    }
    return lesson(id, title, names.join(", "), points, questions.slice(0, 15).map((item) => ({ ...item, rtl: true })));
  }

  function rowsLesson(id, title, description, points, rows) {
    return lesson(id, title, description, points, rows.map(([prompt, answer, wrongs, hint]) => q({ prompt, answer, wrongs, hint, rtl: true })));
  }

