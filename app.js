  function renderVisual(visual) {
    if (visual.kind === "emoji") return `<div class="visual-card emoji-visual">${visual.value}</div>`;
    if (visual.kind === "car") return `<div class="visual-card"><div class="mini-car ${visual.color}"><span></span></div></div>`;
    if (visual.kind === "ball") return `<div class="visual-card"><div class="mini-ball ${visual.color}"></div></div>`;
    if (visual.kind === "balloon") return `<div class="visual-card"><div class="mini-balloon ${visual.color}"></div></div>`;
    if (visual.kind === "house") return `<div class="visual-card"><div class="mini-house ${visual.color}"></div></div>`;
    if (visual.kind === "place") return `<div class="visual-card place-visual"><span>${placeItem(visual.item)}</span><b>${visual.place === "under" ? "▁" : "▔"}</b><i>${visual.place === "house" ? "⌂" : "▭"}</i></div>`;
    return "";
  }

  function placeItem(item) {
    return { book: "📘", ball: "⚽", car: "🏎️", juice: "🧃" }[item] || "●";
  }

  function renderMatchExercise(exercise) {
    const left = exercise.pairs.map((pair) => pair[0]);
    const right = exercise.pairs.map((pair) => pair[1]).slice().reverse();
    const allDone = activeLesson.matched.length === exercise.pairs.length;
    return `
      <div class="question small">${textSpan(exercise.prompt)}</div>
      <div class="match-grid">
        <div class="match-col">
          ${left.map((value) => matchTile(value, "left", exercise.rtl)).join("")}
        </div>
        <div class="match-col">
          ${right.map((value) => matchTile(value, "right", exercise.rtl)).join("")}
        </div>
      </div>
      <div class="feedback">${allDone ? "Все пары найдены!" : "Нажми на две подходящие плитки."}</div>
      ${allDone ? `<button class="primary" data-next-question>Дальше</button>` : ""}
    `;
  }

  function matchTile(value, side, rtl) {
    const done = activeLesson.matched.some((pair) => pair.includes(value));
    const selected = activeLesson.leftPick === value || activeLesson.rightPick === value;
    return `<button class="match-tile ${done ? "done" : ""} ${selected ? "selected" : ""}" dir="${textDirection(value)}" data-match-side="${side}" data-match-value="${escapeAttr(value)}">${textSpan(value)}</button>`;
  }

  function feedbackFor(exercise) {
    if (activeLesson.selected === exercise.answer) return "Верно! Отлично.";
    return "Почти. Посмотри на правильный ответ.";
  }

  function endlessFeedback(exercise) {
    if (activeEndless.selected === exercise.answer) return "Верно! +2 очка.";
    return "Почти. Правильный ответ подсвечен.";
  }

  function renderLessonDone(subject, level) {
    const firstTime = !progress.completed[level.id];
    const bonus = activeLesson.mistakes === 0 ? 10 : 0;
    const practicePoints = Math.max(5, Math.round(level.points * 0.12)) + (activeLesson.mistakes === 0 ? 2 : 0);
    if (firstTime) {
      progress.points += level.points + bonus;
      progress.completed[level.id] = true;
      progress.stars[level.id] = activeLesson.mistakes === 0 ? 3 : activeLesson.mistakes === 1 ? 2 : 1;
    } else {
      progress.points += practicePoints;
    }
    saveProgress();
    const earnedText = firstTime ? `Ты получил ${level.points + bonus} очков.` : `Практика: +${practicePoints} очков.`;
    return `
      <section class="panel">
        <h2 class="section-title">Готово!</h2>
        <p class="muted">${earnedText}</p>
        <p class="muted">Звёзды: ${"★".repeat(progress.stars[level.id] || 1)}</p>
        <div class="quick-actions">
          <button class="primary" data-subject="${subject.id}">Ещё урок</button>
          <button class="ghost" data-route="shop">Магазин</button>
        </div>
      </section>
    `;
  }

