  function lesson(id, title, description, points, exercises) {
    return { id, title, description, points, exercises };
  }

  function mathLesson(id, title, description, points, rows) {
    return lesson(id, title, description, points, rows.map(([prompt, answer, wrongs]) => ({
      type: "choice",
      prompt,
      answer,
      options: orderedOptions(prompt, answer, wrongs),
      numeric: true
    })));
  }

  function heLesson(id, title, description, points, rows) {
    return lesson(id, title, description, points, rows.map(([prompt, answer, wrongs]) => ({
      type: "choice",
      prompt,
      answer,
      options: orderedOptions(prompt, answer, wrongs),
      rtl: /[\u0590-\u05ff]/.test(prompt + answer + wrongs.join(""))
    })));
  }

  function orderedOptions(seed, answer, wrongs) {
    const options = [answer, ...wrongs];
    const shift = Array.from(String(seed)).reduce((sum, char) => sum + char.charCodeAt(0), 0) % options.length;
    return options.slice(shift).concat(options.slice(0, shift));
  }

  function loadProgress() {
    try {
      const raw = localStorage.getItem(STORAGE_KEY);
      if (!raw) return freshProgress();
      return { ...freshProgress(), ...JSON.parse(raw) };
    } catch {
      return freshProgress();
    }
  }

  function freshProgress() {
    return {
      version: 1,
      childName: "Гай",
      points: 0,
      completed: {},
      stars: {},
      inventory: [],
      unlockedGames: [],
      updatedAt: new Date().toISOString()
    };
  }

  function saveProgress() {
    progress.updatedAt = new Date().toISOString();
    localStorage.setItem(STORAGE_KEY, JSON.stringify(progress));
  }

  function clearLessonsFromUrl() {
    const params = new URLSearchParams(window.location.search);
    if (params.get("clearLessons") !== "1") return;
    progress.completed = {};
    progress.stars = {};
    saveProgress();
    params.delete("clearLessons");
    const nextSearch = params.toString();
    const nextUrl = `${window.location.pathname}${nextSearch ? `?${nextSearch}` : ""}${window.location.hash}`;
    window.history.replaceState({}, "", nextUrl);
  }

  function subjectProgress(subject) {
    const total = subject.levels.length;
    const done = subject.levels.filter((level) => progress.completed[level.id]).length;
    return { done, total, pct: total ? Math.round((done / total) * 100) : 0 };
  }

  function setRoute(next) {
    const sameEndless = route.view === "endless" && next.view === "endless" && route.subjectId === next.subjectId;
    route = next;
    activeLesson = null;
    if (!sameEndless) activeEndless = null;
    render();
  }

  function showToast(message) {
    const old = document.querySelector(".toast");
    if (old) old.remove();
    const toast = document.createElement("div");
    toast.className = "toast";
    toast.textContent = message;
    document.body.appendChild(toast);
    clearTimeout(toastTimer);
    toastTimer = setTimeout(() => toast.remove(), 2600);
  }

