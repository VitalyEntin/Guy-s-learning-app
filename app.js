  function bindCommonEvents() {
    app.querySelectorAll("[data-route]").forEach((button) => {
      button.addEventListener("click", () => setRoute({ view: button.dataset.route }));
    });

    app.querySelectorAll("[data-subject]").forEach((button) => {
      const levelId = button.dataset.level;
      button.addEventListener("click", () => {
        if (levelId) setRoute({ view: "lesson", subjectId: button.dataset.subject, levelId });
        else setRoute({ view: "subject", subjectId: button.dataset.subject });
      });
    });

    app.querySelectorAll("[data-endless-subject]").forEach((button) => {
      button.addEventListener("click", () => setRoute({ view: "endless", subjectId: button.dataset.endlessSubject }));
    });

    app.querySelectorAll("[data-start-lesson]").forEach((button) => {
      button.addEventListener("click", startLessonQuestions);
    });

    app.querySelectorAll("[data-answer]").forEach((button) => {
      button.addEventListener("click", () => chooseAnswer(button.dataset.answer));
    });

    app.querySelectorAll("[data-endless-answer]").forEach((button) => {
      button.addEventListener("click", () => chooseEndlessAnswer(button.dataset.endlessAnswer));
    });

    app.querySelectorAll("[data-next-question]").forEach((button) => {
      button.addEventListener("click", nextQuestion);
    });

    app.querySelectorAll("[data-next-endless]").forEach((button) => {
      button.addEventListener("click", nextEndlessQuestion);
    });

    app.querySelectorAll("[data-match-side]").forEach((button) => {
      button.addEventListener("click", () => chooseMatch(button.dataset.matchSide, button.dataset.matchValue));
    });

    app.querySelectorAll("[data-buy]").forEach((button) => {
      button.addEventListener("click", () => buyItem(button.dataset.buy));
    });

    app.querySelectorAll("[data-unlock-game]").forEach((button) => {
      button.addEventListener("click", () => unlockGame(button.dataset.unlockGame));
    });

    app.querySelectorAll("[data-unlock-brick-pack]").forEach((button) => {
      button.addEventListener("click", () => unlockBrickBreakerPack(button.dataset.unlockBrickPack));
    });

    const exportButton = app.querySelector("[data-export]");
    if (exportButton) exportButton.addEventListener("click", exportBackup);

    const importInput = app.querySelector("[data-import]");
    if (importInput) importInput.addEventListener("change", importBackup);

    const resetButton = app.querySelector("[data-reset]");
    if (resetButton) resetButton.addEventListener("click", resetProgress);
  }

  function startLessonQuestions() {
    if (!activeLesson) return;
    activeLesson.introDone = true;
    render();
  }

  function chooseAnswer(answer) {
    if (!activeLesson || activeLesson.answered) return;
    const subject = data.subjects.find((item) => item.id === route.subjectId);
    const level = subject.levels.find((item) => item.id === route.levelId);
    const exercise = level.exercises[activeLesson.index];
    activeLesson.selected = answer;
    activeLesson.answered = true;
    if (answer !== exercise.answer) activeLesson.mistakes += 1;
    render();
  }

  function chooseEndlessAnswer(answer) {
    if (!activeEndless || activeEndless.answered) return;
    const exercise = activeEndless.current;
    activeEndless.selected = answer;
    activeEndless.answered = true;
    activeEndless.total += 1;
    if (answer === exercise.answer) {
      activeEndless.correct += 1;
      activeEndless.earned += 2;
      progress.points += 2;
      saveProgress();
    }
    render();
  }

  function chooseMatch(side, value) {
    if (!activeLesson) return;
    const subject = data.subjects.find((item) => item.id === route.subjectId);
    const level = subject.levels.find((item) => item.id === route.levelId);
    const exercise = level.exercises[activeLesson.index];

    if (side === "left") activeLesson.leftPick = value;
    if (side === "right") activeLesson.rightPick = value;

    if (activeLesson.leftPick && activeLesson.rightPick) {
      const good = exercise.pairs.some((pair) => pair[0] === activeLesson.leftPick && pair[1] === activeLesson.rightPick);
      if (good) {
        activeLesson.matched.push([activeLesson.leftPick, activeLesson.rightPick]);
      } else {
        activeLesson.mistakes += 1;
      }
      activeLesson.leftPick = null;
      activeLesson.rightPick = null;
    }
    render();
  }

  function nextQuestion() {
    if (!activeLesson) return;
    activeLesson.index += 1;
    activeLesson.answered = false;
    activeLesson.selected = null;
    activeLesson.matched = [];
    activeLesson.leftPick = null;
    activeLesson.rightPick = null;
    render();
  }

  function nextEndlessQuestion() {
    if (!activeEndless) return;
    const subject = data.subjects.find((item) => item.id === activeEndless.subjectId);
    const pool = subject ? endlessPool(subject) : [];
    if (!pool.length) {
      activeEndless = null;
      render();
      return;
    }
    const previousKey = activeEndless.current ? activeEndless.current.key : "";
    activeEndless.current = pickEndlessExercise(pool, previousKey);
    activeEndless.answered = false;
    activeEndless.selected = null;
    render();
  }

  function buyItem(itemId) {
    const item = data.shop.find((entry) => entry.id === itemId);
    if (!item || progress.inventory.includes(item.id) || progress.points < item.price) return;
    progress.points -= item.price;
    progress.inventory.push(item.id);
    saveProgress();
    showToast(`Куплено: ${item.name}`);
    render();
  }

  function unlockGame(gameId) {
    const game = games.find((entry) => entry.id === gameId);
    if (!game || progress.unlockedGames.includes(game.id) || progress.points < game.price) return;
    progress.points -= game.price;
    progress.unlockedGames.push(game.id);
    saveProgress();
    showToast(`Игра открыта: ${game.title}`);
    render();
  }

  function unlockBrickBreakerPack(packId) {
    const pack = BRICK_BREAKER_PACKS.find((entry) => entry.id === packId);
    if (!pack || progress.unlockedGames.includes(pack.id) || progress.points < pack.price) return;
    if (pack.id === BRICK_BREAKER_PACKS[1].id && !progress.unlockedGames.includes(BRICK_BREAKER_PACKS[0].id)) return;
    progress.points -= pack.price;
    progress.unlockedGames.push(pack.id);
    saveProgress();
    showToast(`Игра открыта: ${pack.label}`);
    render();
  }

  function exportBackup() {
    const blob = new Blob([JSON.stringify(progress, null, 2)], { type: "application/json" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `guy-progress-${new Date().toISOString().slice(0, 10)}.json`;
    link.click();
    URL.revokeObjectURL(url);
    showToast("Бэкап скачан.");
  }

  function importBackup(event) {
    const file = event.target.files && event.target.files[0];
    if (!file) return;
    const reader = new FileReader();
    reader.onload = () => {
      try {
        const imported = JSON.parse(String(reader.result));
        progress = { ...freshProgress(), ...imported };
        saveProgress();
        showToast("Бэкап загружен.");
        render();
      } catch {
        showToast("Не получилось прочитать файл.");
      }
    };
    reader.readAsText(file);
  }

  function resetProgress() {
    if (!confirm("Сбросить демо-прогресс?")) return;
    progress = freshProgress();
    saveProgress();
    showToast("Демо-прогресс сброшен.");
    render();
  }

  function escapeAttr(value) {
    return String(value).replace(/"/g, "&quot;");
  }

  function escapeHtml(value) {
    return String(value)
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;");
  }

  function normalizeText(value) {
    return String(value).replace(/<</g, "«").replace(/>>/g, "»");
  }

  function textDirection(value) {
    const text = normalizeText(value);
    const hebrew = (text.match(/[\u0590-\u05ff]/g) || []).length;
    const latinOrCyrillic = (text.match(/[A-Za-zА-Яа-яЁё0-9]/g) || []).length;
    return hebrew > latinOrCyrillic ? "rtl" : "ltr";
  }

  function textSpan(value) {
    const text = normalizeText(value);
    return `<span class="text-run" dir="${textDirection(text)}">${escapeHtml(text)}</span>`;
  }

  ["contextmenu", "selectstart", "dragstart"].forEach((eventName) => {
    document.addEventListener(eventName, (event) => {
      const target = event.target;
      if (target && target.closest && target.closest("button, .app-shell")) event.preventDefault();
    }, { capture: true });
  });

  if ("serviceWorker" in navigator) {
    window.addEventListener("load", () => {
      navigator.serviceWorker.register("./sw.js").catch(() => {});
    });
  }

  render();
